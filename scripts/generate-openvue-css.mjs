/**
 * Renders the OpenVue theme to a static stylesheet.
 *
 * In styled mode OpenVue injects its CSS from the browser at runtime, which is
 * fine for hydrated components and useless for statically rendered ones: this
 * site renders nearly all of its OpenVue components at build time with no
 * client directive, so nothing ever runs to inject their styles.
 *
 * The style objects behind each component expose the same string generators the
 * Nuxt module uses for SSR, and they touch no DOM. Calling them here produces
 * the stylesheet ahead of time: no runtime injection, no unstyled flash, no
 * JavaScript shipped for a card.
 *
 * Run by `pnpm run dev` and `pnpm run build`. Output is generated, gitignored,
 * and never edited by hand.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Theme } from '@openvue/themes';

import { components, themeConfig } from '../src/openvue-theme.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/styles/openvue.generated.css');

// The generators return complete <style> elements, ready for a <head>. We want
// the CSS itself.
const unwrap = (markup) => String(markup ?? '').replace(/<style[^>]*>|<\/style>/g, '');

Theme.setTheme(themeConfig);

const load = async (name) => {
    const module = await import(`openvue/${name}/style`);

    return module.default;
};

// Design tokens and the shared `.p-component` layer, emitted once. Any
// component's style object can produce them; they are identical.
const base = await load(components[0]);
const chunks = [unwrap(base.getCommonThemeStyleSheet())];

for (const name of components) {
    const style = await load(name);

    // Structural CSS is empty in styled mode, where the theme carries the
    // rules, but it is what unstyled mode would emit. Cheap to include.
    chunks.push(unwrap(style.getStyleSheet()));
    chunks.push(unwrap(style.getThemeStyleSheet()));
}

const css = [
    '/* Generated by scripts/generate-openvue-css.mjs. Do not edit. */',
    ...chunks.filter((chunk) => chunk.trim())
].join('\n');

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `${css}\n`, 'utf8');

const kb = (Buffer.byteLength(css) / 1024).toFixed(1);

console.log(`[openvue] ${components.length} components -> src/styles/openvue.generated.css (${kb} kB)`);

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Theme } from '@openvue/themes';

import { components, themeConfig } from '../src/openvue-theme.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = resolve(root, 'src/styles/openvue.generated.css');

const unwrap = (markup) => String(markup ?? '').replace(/<style[^>]*>|<\/style>/g, '');

Theme.setTheme(themeConfig);

const load = async (name) => {
    const module = await import(`openvue/${name}/style`);

    return module.default;
};

const base = await load(components[0]);
const chunks = [unwrap(base.getCommonThemeStyleSheet())];

for (const name of components) {
    const style = await load(name);

    chunks.push(unwrap(style.getStyleSheet()));
    chunks.push(unwrap(style.getThemeStyleSheet()));
}

const css = [
    '/* Generated by scripts/generate-openvue-css.mjs. Do not edit. */',
    ...chunks.filter((chunk) => chunk.trim())
].join('\n');

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `${css}\n`, 'utf8');

const kb = (Buffer.byteLength(css) / 1024).toFixed(1);

console.log(`[openvue] ${components.length} components -> src/styles/openvue.generated.css (${kb} kB)`);
